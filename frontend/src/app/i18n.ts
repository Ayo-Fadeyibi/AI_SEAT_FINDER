export type Lang = "en" | "zh";

const LANG_STORAGE_KEY = "findaspot_lang";

/** Shared en/zh toggle, persisted so it stays put across the landing page,
 * finder, and admin panel (they each mount their own instance of this
 * hook, but all read/write the same localStorage key). */
export function useLang(): [Lang, () => void] {
  const [lang, setLang] = useState<Lang>(() => {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    return saved === "zh" || saved === "en" ? saved : "en";
  });
  const toggleLang = () => {
    setLang(prev => {
      const next: Lang = prev === "en" ? "zh" : "en";
      localStorage.setItem(LANG_STORAGE_KEY, next);
      return next;
    });
  };
  return [lang, toggleLang];
}

